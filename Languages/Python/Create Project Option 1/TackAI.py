class LayerDense:
    def __init__(self, n_input, n_neurons):
        #Generate weights and biases
        self.weights = 0.01 * np.random.randn(n_input, n_neurons)
        self.biases = np.zeros((1, n_neurons))
        
    def forward(self, inputs):
        self.inputs = inputs
        self.outputs = np.dot(inputs, self.weights) + self.biases
    
    def backward(self, dvalues, lr):
        self.weights -= lr * np.dot(self.inputs.T, dvalues)
        self.biases -= lr * np.sum(dvalues, axis=0, keepdims=True)
        self.dinputs = np.dot(dvalues, self.weights.T)
    
class Tanh:
    def forward(self, inputs):
        self.inputs = inputs
        self.outputs = np.tanh(inputs)
    
    def backward(self, dvalues):
        self.dinputs = dvalues * (1 - np.tanh(self.inputs) ** 2)

class Softmax:
    def forward(self, inputs):
        self.exp_values = np.exp(inputs)
        self.outputs = self.exp_values / np.sum(self.exp_values, axis=1, keepdims=True)
    
    def backward(self, dvalues):
        self.dinputs = np.empty_like(dvalues)
        for index, (single_dvalue, single_output) in enumerate(zip(dvalues, self.outputs)):
            single_output = single_output.reshape(-1,1)
            martix = np.diagflat(single_output) - np.dot(single_output, single_output.T)
            self.dinputs[index] = np.dot(martix, single_dvalue)

class Loss:
    def calc(self, y_pred, y_true):
        return -np.sum(y_true*np.log(y_pred))
    def backward(self, dvalues, y_true):
        samples = len(dvalues)
        self.dinputs = -y_true / dvalues
        self.dinputs = self.dinputs / samples
